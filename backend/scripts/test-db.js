#!/usr/bin/env node
'use strict';

// Disposable PostgreSQL cluster for integration tests.
//
// It never touches the development server: it creates a *separate* cluster
// (own data directory, own port, loopback-only, no Unix socket) and a single
// database named `medilink_test`. Credentials are random per cluster and are
// written only to backend/.env.test (git-ignored, mode 600) — never printed.
//
//   node scripts/test-db.js setup     create cluster + db, apply migrations
//   node scripts/test-db.js start     start an existing cluster
//   node scripts/test-db.js stop      stop the cluster
//   node scripts/test-db.js status    print identity (no credentials)
//   node scripts/test-db.js destroy   stop and delete the cluster directory
//
// Environment overrides: MEDILINK_TEST_PGDATA (data directory),
// MEDILINK_TEST_PGPORT (default 55439), MEDILINK_TEST_PGBIN (binary dir).

const { spawnSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const BACKEND = path.join(__dirname, '..');
const ENV_TEST = path.join(BACKEND, '.env.test');
const DATA_DIR = path.resolve(process.env.MEDILINK_TEST_PGDATA || path.join(os.tmpdir(), 'medilink-test-postgres'));
const PORT = String(process.env.MEDILINK_TEST_PGPORT || '55439');
const DB_NAME = 'medilink_test';
const DB_USER = 'medilink_test_owner';
const MARKER = path.join(DATA_DIR, '.medilink-disposable-test-cluster');
const bin = (name) => (process.env.MEDILINK_TEST_PGBIN ? path.join(process.env.MEDILINK_TEST_PGBIN, name) : name);

const fail = (message) => { console.error(`test-db: ${message}`); process.exit(1); };

const run = (cmd, args, { env = {}, allowFail = false } = {}) => {
  const result = spawnSync(bin(cmd), args, { env: { ...process.env, ...env }, encoding: 'utf8' });
  if (result.error) fail(`could not run ${cmd}: ${result.error.code || result.error.message}`);
  if (result.status !== 0 && !allowFail) {
    // stderr from PostgreSQL tools does not contain the password (passed via env/pwfile).
    fail(`${cmd} failed (exit ${result.status}): ${String(result.stderr || '').trim().split('\n').slice(-3).join(' | ')}`);
  }
  return result;
};

const readEnvTest = () => {
  if (!fs.existsSync(ENV_TEST)) return {};
  return Object.fromEntries(fs.readFileSync(ENV_TEST, 'utf8').split('\n')
    .filter((line) => /^[A-Z_]+=/.test(line))
    .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]));
};

const assertSafeTarget = () => {
  if (PORT === '5432') fail('refusing to use port 5432 (the default development PostgreSQL port)');
  if (!/_test$/.test(DB_NAME)) fail('database name must end in _test');
};

const isRunning = () => run('pg_ctl', ['-D', DATA_DIR, 'status'], { allowFail: true }).status === 0;

const start = () => {
  if (!fs.existsSync(MARKER)) fail(`no disposable test cluster at ${DATA_DIR}; run "setup" first`);
  if (isRunning()) return;
  run('pg_ctl', ['-D', DATA_DIR, '-l', path.join(DATA_DIR, 'server.log'), '-w', '-o',
    `-p ${PORT} -c listen_addresses=127.0.0.1 -c unix_socket_directories=''`, 'start']);
};

const stop = () => {
  if (fs.existsSync(MARKER) && isRunning()) run('pg_ctl', ['-D', DATA_DIR, '-w', '-m', 'fast', 'stop']);
};

function setup() {
  assertSafeTarget();
  let password = readEnvTest().MEDILINK_TEST_DB_PASSWORD;

  if (!fs.existsSync(MARKER)) {
    if (fs.existsSync(DATA_DIR) && fs.readdirSync(DATA_DIR).length) {
      fail(`${DATA_DIR} exists and is not a MediLink disposable test cluster; refusing to touch it`);
    }
    password = crypto.randomBytes(24).toString('hex');
    fs.mkdirSync(DATA_DIR, { recursive: true, mode: 0o700 });
    const pwfile = path.join(os.tmpdir(), `medilink-test-pw-${process.pid}`);
    fs.writeFileSync(pwfile, password, { mode: 0o600 });
    try {
      run('initdb', ['-D', DATA_DIR, '-U', DB_USER, '-A', 'scram-sha-256', `--pwfile=${pwfile}`, '-E', 'UTF8', '--no-locale']);
    } finally {
      fs.rmSync(pwfile, { force: true });
    }
    fs.writeFileSync(MARKER, `MediLink disposable integration-test cluster. Safe to delete.\nport=${PORT}\ndatabase=${DB_NAME}\n`);
  }
  if (!password) fail('cluster exists but backend/.env.test has no password; run "destroy" then "setup"');

  start();
  const pgEnv = { PGPASSWORD: password };
  const exists = run('psql', ['-h', '127.0.0.1', '-p', PORT, '-U', DB_USER, '-d', 'postgres', '-Atc',
    `SELECT 1 FROM pg_database WHERE datname = '${DB_NAME}'`], { env: pgEnv }).stdout.trim() === '1';
  if (!exists) run('createdb', ['-h', '127.0.0.1', '-p', PORT, '-U', DB_USER, DB_NAME], { env: pgEnv });

  const url = `postgresql://${DB_USER}:${password}@127.0.0.1:${PORT}/${DB_NAME}?schema=public`;
  fs.writeFileSync(ENV_TEST, [
    '# Disposable integration-test database (generated by scripts/test-db.js). Never commit.',
    `TEST_DATABASE_URL=${url}`,
    `MEDILINK_INTEGRATION_TEST_DB_CONFIRM=${DB_NAME}`,
    `MEDILINK_TEST_DB_PASSWORD=${password}`,
    '',
  ].join('\n'), { mode: 0o600 });

  // The guard must accept the target before anything is migrated.
  require('dotenv').config({ path: path.join(BACKEND, '.env') });
  const { assertSafeTestDatabase } = require('../tests-integration/support/databaseGuard');
  const target = assertSafeTestDatabase({ ...process.env, TEST_DATABASE_URL: url, MEDILINK_INTEGRATION_TEST_DB_CONFIRM: DB_NAME });

  const migrate = spawnSync('npx', ['prisma', 'migrate', 'deploy'], {
    cwd: BACKEND, encoding: 'utf8', env: { ...process.env, DATABASE_URL: url },
  });
  if (migrate.status !== 0) fail('prisma migrate deploy failed against the test database');
  const applied = (migrate.stdout.match(/(\d+) migrations? found/) || [])[1];
  console.log(`test-db: ready — host=${target.host} port=${target.port} database=${target.database} (migrations found: ${applied || 'n/a'})`);
}

function status() {
  const running = fs.existsSync(MARKER) && isRunning();
  console.log(`test-db: cluster=${fs.existsSync(MARKER) ? 'present' : 'absent'} running=${running} host=127.0.0.1 port=${PORT} database=${DB_NAME}`);
}

function destroy() {
  if (!fs.existsSync(DATA_DIR)) { console.log('test-db: nothing to destroy'); return; }
  if (!fs.existsSync(MARKER)) fail(`${DATA_DIR} is not a MediLink disposable test cluster; refusing to delete it`);
  stop();
  fs.rmSync(DATA_DIR, { recursive: true, force: true });
  fs.rmSync(ENV_TEST, { force: true });
  console.log('test-db: disposable test cluster deleted');
}

const commands = { setup, start: () => { start(); status(); }, stop: () => { stop(); status(); }, status, destroy };
const command = process.argv[2];
if (!commands[command]) fail(`usage: node scripts/test-db.js <${Object.keys(commands).join('|')}>`);
commands[command]();
